import { randomUUID } from 'node:crypto';
import { HttpStatus, Injectable, Logger } from '@nestjs/common';
import { AppError } from '../common/app-error.js';
import { PrismaService } from '../prisma/prisma.service.js';
import { StorageService } from '../storage/storage.service.js';
import {
  imageKeys,
  MAX_IMAGES_PER_PRODUCT,
  processProductImage,
  storageKeyFor,
} from './image-processing.js';

/** Photos uploaded but never saved with a product are removed after this time. */
const ORPHAN_TTL_MS = 24 * 60 * 60 * 1000;

export interface ImageView {
  id: string;
  url: string | null;
  thumbUrl: string | null;
  width: number;
  height: number;
  position: number;
  isPrimary: boolean;
}

@Injectable()
export class ImagesService {
  private readonly logger = new Logger(ImagesService.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly storage: StorageService,
  ) {}

  /**
   * Uploads a photo for a product being created (draft id generated by the
   * client) or edited. The photo stays "pending" (productId = null) until the
   * product is saved, but its object key already lives under the product.
   */
  async upload(tenantId: string, userId: string, productId: string, file: Buffer): Promise<ImageView> {
    this.storage.assertConfigured();

    const existing = await this.prisma.product.findUnique({ where: { id: productId }, select: { tenantId: true } });
    if (existing && existing.tenantId !== tenantId) {
      throw new AppError(HttpStatus.NOT_FOUND, 'PRODUCT_NOT_FOUND', 'No se encontró el producto.');
    }
    const prefix = `tenants/${tenantId}/products/${productId}/`;
    const count = await this.prisma.productImage.count({ where: { tenantId, storageKey: { startsWith: prefix } } });
    if (count >= MAX_IMAGES_PER_PRODUCT) {
      throw new AppError(
        HttpStatus.BAD_REQUEST,
        'TOO_MANY_IMAGES',
        `Cada prenda puede tener hasta ${MAX_IMAGES_PER_PRODUCT} fotos.`,
      );
    }

    const processed = await processProductImage(file);
    const id = randomUUID();
    const storageKey = storageKeyFor(tenantId, productId, id);
    const keys = imageKeys(storageKey);
    try {
      await Promise.all([
        this.storage.put(keys.main, processed.main, processed.contentType),
        this.storage.put(keys.thumb, processed.thumb, processed.contentType),
      ]);
    } catch (error) {
      if (error instanceof AppError) throw error;
      this.logger.error(`Photo upload to storage failed: ${(error as Error).name}`);
      await this.storage.deleteMany([keys.main, keys.thumb]).catch(() => undefined);
      throw new AppError(HttpStatus.BAD_GATEWAY, 'STORAGE_ERROR', 'No pudimos guardar la foto. Intenta de nuevo.');
    }

    const image = await this.prisma.productImage.create({
      data: {
        id,
        tenantId,
        uploadedById: userId,
        storageKey,
        contentType: processed.contentType,
        sizeBytes: processed.main.length,
        width: processed.width,
        height: processed.height,
        position: count,
      },
    });
    void this.cleanupOrphans(tenantId);
    return this.toView(image);
  }

  /** Deletes a photo that has not been saved with a product yet. */
  async deletePending(tenantId: string, id: string): Promise<void> {
    const image = await this.prisma.productImage.findFirst({ where: { id, tenantId, productId: null } });
    if (!image) throw new AppError(HttpStatus.NOT_FOUND, 'IMAGE_NOT_FOUND', 'No se encontró la foto.');
    await this.prisma.productImage.delete({ where: { id: image.id } });
    await this.removeObjects([image.storageKey]);
  }

  async removeObjects(storageKeys: string[]): Promise<void> {
    const keys = storageKeys.flatMap((k) => Object.values(imageKeys(k)));
    try {
      await this.storage.deleteMany(keys);
    } catch (error) {
      // The DB no longer references them; log so they can be purged later.
      this.logger.warn(`Could not delete ${keys.length} storage objects: ${(error as Error).name}`);
    }
  }

  async toView(image: {
    id: string;
    storageKey: string;
    width: number;
    height: number;
    position: number;
    isPrimary: boolean;
  }): Promise<ImageView> {
    const keys = imageKeys(image.storageKey);
    const [url, thumbUrl] = await Promise.all([this.storage.signedUrl(keys.main), this.storage.signedUrl(keys.thumb)]);
    return {
      id: image.id,
      url,
      thumbUrl,
      width: image.width,
      height: image.height,
      position: image.position,
      isPrimary: image.isPrimary,
    };
  }

  /** Reads the optimized main version (used to send photos to the AI). */
  async readMain(storageKey: string): Promise<Buffer> {
    return this.storage.get(imageKeys(storageKey).main);
  }

  /** Removes this tenant's photos that were uploaded but never saved with a product. */
  private async cleanupOrphans(tenantId: string): Promise<void> {
    try {
      const cutoff = new Date(Date.now() - ORPHAN_TTL_MS);
      const orphans = await this.prisma.productImage.findMany({
        where: { tenantId, productId: null, createdAt: { lt: cutoff } },
        select: { id: true, storageKey: true },
        take: 50,
      });
      if (orphans.length === 0) return;
      await this.prisma.productImage.deleteMany({ where: { id: { in: orphans.map((o) => o.id) }, productId: null } });
      await this.removeObjects(orphans.map((o) => o.storageKey));
    } catch (error) {
      this.logger.warn(`Orphan photo cleanup failed: ${(error as Error).name}`);
    }
  }
}
